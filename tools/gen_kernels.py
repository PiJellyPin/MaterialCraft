#!/usr/bin/env python3
"""Builds src/kernels/*.wgsl from the fragments in src/kernels/parts (the Rust code include_str!s the results).

Run from the repository root after editing a fragment:  python3 tools/gen_kernels.py
"""
import os, sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "kernels")
parts = os.path.join(root, "parts")


def rd(name):
    with open(os.path.join(parts, name), encoding="utf-8") as f:
        return f.read()


def samp(suffix, buf):
    return rd("samp.tpl").replace("$S", suffix).replace("$B", buf)


SAMPLERS = {"A": "ia", "B": "ib", "C": "ic", "D": "id4", "E": "ie", "F": "if_", "G": "ig"}

# output name -> (head, fragments before the body, samplers, body)
KERNELS = {
    "ops_a": ("head.wgsl", ["common.wgsl"], "ABC", "ops_a.wgsl"),
}
EXTRA = os.path.join(parts, "kernels.list")
if os.path.exists(EXTRA):
    for line in open(EXTRA, encoding="utf-8"):
        line = line.split("#")[0].strip()
        if not line:
            continue
        name, head, pre, sm, body = [x.strip() for x in line.split("|")]
        KERNELS[name] = (head, [x for x in pre.split(",") if x], sm, body)

for name, (head, pre, sm, body) in KERNELS.items():
    out = "// generated by tools/gen_kernels.py from src/kernels/parts - edit the fragments, not this file\n"
    out += rd(head)
    for p in pre:
        out += rd(p)
    for s in sm:
        out += samp(s, SAMPLERS[s])
    out += rd(body)
    with open(os.path.join(root, name + ".wgsl"), "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    print("wrote", name)
